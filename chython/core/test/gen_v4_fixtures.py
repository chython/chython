# Public compounds, each carrying a stated parity of a different kind, plus two that carry none.
STRUCTURES = (
    'C[C@H](N)C(=O)O',                      # L-alanine, one tetrahedral centre
    'C/C=C/C',                              # trans-2-butene, one cis/trans unit
    'C/C=C\\C',                             # cis-2-butene
    'O[C@@H]1[C@H](O)[C@@H](O)[C@H](O)[C@H](O)[C@H]1O',   # myo-inositol, six centres
    'C[C@H](O)[C@@H](C)O',                  # two centres, one molecule
    'CC(=O)Oc1ccccc1C(=O)O',                # aspirin, no stereo
    'c1ccccc1',                             # benzene, no stereo
)


def _answers(mol):
    return {'parities': {n: mol.parity_of(n) for n in mol.atom_numbers if mol.parity_of(n)},
            'wedges': mol.wedges(),
            'stereo_groups': mol.stereo_groups()}


def _sgroup_and_stereo():
    """One record with S-groups AND a stereocentre.

    The only record that reaches the S-group and blob memcpy arms of the arena's segment carry; no
    molecule built from SMILES alone reaches those arms.  `set_sgroups` is the only constructor in
    the tree for this path.  Read `test_sgroups.py` for the record shape (`{'type': b'DAT',
    'name': b'...', 'atoms': (id, ...), 'data': [b'...'], 'index': 1}`).
    """
    mol = read_smiles('C[C@H](N)C(=O)O')
    ids = list(mol.atom_numbers)
    mol.set_sgroups([{'type': b'DAT', 'name': b'BATCH', 'atoms': (ids[1],),
                      'data': [b'lot-42'], 'index': 1}])
    return mol


def main():
    here = Path(__file__).parent
    records = []
    answers = {}
    sgroup_mol = _sgroup_and_stereo()
    for mol in [read_smiles(text) for text in STRUCTURES] + [sgroup_mol]:
        raw = mol.to_bytes()
        assert raw[4] == 4, 'this build writes arena version %d, not 4' % raw[4]
        records.append(raw)
        answers[str(mol)] = _answers(mol)
    sgroup_raw = records[-1]
    assert sgroup_mol.sgroups, 'the S-group record did not survive; check set_sgroups'
    with gzip_open(here / 'arena_v4_corpus.bin.gz', 'wb') as f:
        for raw in records:
            f.write(len(raw).to_bytes(4, 'little'))
            f.write(raw)
    with open(here / 'v4_fixtures.py', 'w') as f:
        f.write(HEADER)
        f.write('# FROZEN. Generated by gen_v4_fixtures.py against a build whose STRUCT_VERSION was 4.\n'
                '# Nothing regenerates this: a later build cannot write a version-4 buffer.\n'
                '\nV4_ANSWERS = ')
        f.write(pformat(answers, width=110))
        f.write('\n\n# The one record carrying S-groups and a stereocentre together.\nV4_SGROUP_STEREO_BYTES = ')
        f.write(repr(sgroup_raw))
        f.write('\n')


if __name__ == '__main__':
    main()
