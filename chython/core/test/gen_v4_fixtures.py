"""Freeze a corpus of arena version-4 buffers and the answers they must still give.

Run against a build whose `STRUCT_VERSION` is 4.  The output is committed; no later build writes
version-4 bytes, so this file cannot be regenerated.

    python -m chython.core.test.gen_v4_fixtures
"""
from gzip import open as gzip_open
from pathlib import Path
from pprint import pformat

from chython.core._core import read_smiles


# The generated file is source and carries the tree's header like any other; it cannot be regenerated
# by a later build, so the header is written here rather than added by hand afterwards.
